const AGENT_SESSION_ENV_KEYS = [
  "TICKETS_DIR",
  "TLH_TICKETS_DIR_AUTO",
  "PI_SESSION_ID",
  "PI_SESSION_FILE",
  "PI_BB_TOOLS_FILE",
  "PI_SUBAGENT_CHILD",
  "PI_SUBAGENT_INHERIT_PROJECT_CONTEXT",
  "PI_SUBAGENT_INHERIT_SKILLS",
  "PI_SUBAGENT_PROJECT_AGENT_GUIDANCE",
  "PI_SUBAGENT_TK_TICKET_ID",
  "PI_SUBAGENT_SUPERVISOR_BRIDGE",
  "PI_SUBAGENT_SUPERVISOR_CHANNEL_DIR",
  "PI_SUBAGENT_ORCHESTRATOR_SESSION_ID",
  "PI_SUBAGENT_RUN_ID",
  "PI_SUBAGENT_CHILD_AGENT",
  "PI_SUBAGENT_CHILD_INDEX",
  "PI_SUBAGENT_STEER_INBOX",
  "PI_SUBAGENT_PARENT_SESSION",
  "PI_SUBAGENT_PARENT_EVENT_SINK",
  "PI_SUBAGENT_PARENT_CONTROL_INBOX",
  "PI_SUBAGENT_PARENT_ROOT_RUN_ID",
  "PI_SUBAGENT_PARENT_RUN_ID",
  "PI_SUBAGENT_PARENT_CHILD_INDEX",
  "PI_SUBAGENT_PARENT_DEPTH",
  "PI_SUBAGENT_PARENT_PATH",
  "PI_SUBAGENT_PARENT_CAPABILITY_TOKEN",
] as const;

export function stripAgentSessionEnv(
  env: NodeJS.ProcessEnv,
): NodeJS.ProcessEnv {
  const result = { ...env };
  for (const key of AGENT_SESSION_ENV_KEYS) {
    delete result[key];
  }
  if (result.MCP_DIRECT_TOOLS === "__none__") {
    delete result.MCP_DIRECT_TOOLS;
  }
  return result;
}
